/**
 * Staging acceptance profile — turn the FULL feature-flag surface ON in one pass.
 *
 * Why this exists: the admin portal at /admin/feature-flags toggles one flag at a
 * time. Acceptance testing wants every surface live at once, and the flag set is
 * 86 keys wide. This script derives the key list from `FLAG_ENV_MAP` at runtime,
 * so it can never drift from the flag registry — adding a flag automatically
 * includes it here.
 *
 * SAFETY
 *   - Refuses to run when APP_MODE/NODE_ENV is production unless --force.
 *   - Prints the target host (redacted) and requires --yes to write.
 *   - Default mode is a dry run.
 *   - Every write stamps `updated_by = 'staging-flag-profile'` so the change is
 *     attributable in the admin portal and in the table itself.
 *
 * USAGE (from the repo root)
 *   # 1. Preview the diff against the target database (no writes):
 *   DATABASE_URL=... node --env-file=.env --import tsx/esm \
 *     apps/server/src/scripts/staging-flag-profile.ts
 *
 *   # 2. Emit a SQL script instead of connecting (hand this to ops/psql):
 *   node --import tsx/esm apps/server/src/scripts/staging-flag-profile.ts --sql
 *
 *   # 3. Apply:
 *   DATABASE_URL=... node --env-file=.env --import tsx/esm \
 *     apps/server/src/scripts/staging-flag-profile.ts --yes
 *
 *   # Keep additional flags off (comma-separated camelCase keys):
 *   ... --keep-off quipInspirationChipsEnabled,recapSharePosterEnabled
 *
 * Env note: node's --env-file does NOT override variables already present in the
 * process environment, so the DATABASE_URL=... prefix wins over .env.
 */

import { eq } from "drizzle-orm";

import { featureFlags } from "@shared/schema";

import { db } from "../db";
import { FLAG_ENV_MAP } from "../lib/featureFlags";

/**
 * Flags that stay OFF in the acceptance profile, with the reason. Keep this list
 * short and justified — anything here is untestable on staging.
 */
const KEEP_OFF: Record<string, string> = {
  matchingOperatorReviewEnabled:
    "开着它，每次排桌都会被扣住等人工审批，后续链路（通知/场地分配/邀请奖励）不会执行，端到端验收会卡死。要验收「人工审核」本身时再单独打开。",
};

/** Extra flags to keep off via --keep-off. */
function parseArgs(argv: string[]) {
  const keepOff: string[] = [];
  let yes = false;
  let sql = false;
  let force = false;

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--yes") yes = true;
    else if (arg === "--sql") sql = true;
    else if (arg === "--force") force = true;
    else if (arg === "--keep-off") {
      const value = argv[i + 1] ?? "";
      keepOff.push(...value.split(",").map((k) => k.trim()).filter(Boolean));
      i += 1;
    }
  }

  return { yes, sql, force, keepOff };
}

/** Redact credentials before printing a connection target. */
function describeTarget(databaseUrl: string | undefined): string {
  if (!databaseUrl) return "(DATABASE_URL 未设置)";
  try {
    const url = new URL(databaseUrl);
    return `${url.hostname}:${url.port || "5432"}${url.pathname}`;
  } catch {
    return "(无法解析 DATABASE_URL)";
  }
}

function sqlLiteral(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

async function main() {
  const { yes, sql, force, keepOff } = parseArgs(process.argv.slice(2));

  const appMode = process.env.APP_MODE ?? process.env.NODE_ENV ?? "";
  if (appMode === "production" && !force) {
    console.error(
      "[staging-flag-profile] APP_MODE/NODE_ENV=production — refusing to run. Pass --force only if this is intentional.",
    );
    process.exit(1);
  }

  const offReasons = new Map<string, string>(Object.entries(KEEP_OFF));
  for (const key of keepOff) {
    if (!(key in FLAG_ENV_MAP)) {
      console.error(`[staging-flag-profile] --keep-off key not in FLAG_ENV_MAP: ${key}`);
      process.exit(1);
    }
    offReasons.set(key, "通过 --keep-off 指定");
  }

  const allKeys = Object.keys(FLAG_ENV_MAP);
  const onKeys = allKeys.filter((key) => !offReasons.has(key));

  console.log(`[staging-flag-profile] 目标: ${describeTarget(process.env.DATABASE_URL)}`);
  console.log(`[staging-flag-profile] 全量键: ${allKeys.length}，本次开启: ${onKeys.length}，保持关闭: ${offReasons.size}`);

  if (sql) {
    const values = allKeys
      .map((key) => {
        const value = offReasons.has(key) ? "false" : "true";
        const description = offReasons.get(key) ?? null;
        return `  (${sqlLiteral(key)}, ${sqlLiteral(value)}, ${description ? sqlLiteral(description) : "NULL"}, 'staging-flag-profile', now())`;
      })
      .join(",\n");

    console.log("\n-- Staging acceptance profile (generated by staging-flag-profile.ts)");
    console.log("-- Apply with: psql \"$DATABASE_URL\" -f <this file>");
    console.log("INSERT INTO feature_flags (key, value, description, updated_by, updated_at) VALUES");
    console.log(values);
    console.log(
      "ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = now(), updated_by = 'staging-flag-profile';",
    );
    console.log(
      "\n-- Note: the API caches flags for 5s; a running server picks this up within 5 seconds.",
    );
    return;
  }

  const existing = await db
    .select({ key: featureFlags.key, value: featureFlags.value })
    .from(featureFlags);
  const existingMap = new Map(
    existing.map((row: { key: string; value: string }) => [row.key, row.value.toLowerCase() === "true"]),
  );

  const changes: string[] = [];
  for (const key of allKeys) {
    const desired = !offReasons.has(key);
    const current = existingMap.get(key);
    if (current === desired) continue;
    changes.push(
      `  ${current === undefined ? "(未设置)" : current ? "true" : "false"} → ${desired ? "true" : "false"}  ${key}${offReasons.has(key) ? `  [保持关闭] ${offReasons.get(key)}` : ""}`,
    );
  }

  console.log(
    `[staging-flag-profile] 已有记录: ${existing.length}/${allKeys.length}，需要变更: ${changes.length}`,
  );
  if (changes.length === 0) {
    console.log("[staging-flag-profile] 已是目标状态，无需写入。");
    return;
  }
  console.log(changes.join("\n"));

  if (!yes) {
    console.log("\n[staging-flag-profile] 预演模式，未写入。加 --yes 应用（或 --sql 输出 SQL）。");
    return;
  }

  await db.transaction(async (tx: any) => {
    for (const key of allKeys) {
      const value = offReasons.has(key) ? "false" : "true";
      const description = offReasons.get(key) ?? null;
      await tx
        .insert(featureFlags)
        .values({ key, value, description, updatedBy: "staging-flag-profile" })
        .onConflictDoUpdate({
          target: featureFlags.key,
          set: { value, description, updatedBy: "staging-flag-profile", updatedAt: new Date() },
        });
    }
  });

  console.log(`[staging-flag-profile] 已写入 ${allKeys.length} 个开关（updated_by=staging-flag-profile）。`);
  console.log("[staging-flag-profile] 服务端缓存 TTL 5s，稍等片刻再验收。");
  console.log(
    "[staging-flag-profile] 提示：Flash（街头盲盒）仍受深圳定位硬门限制，异地验收需在深圳坐标下测试，或临时关闭 flashShenzhenLocationGateEnabled。",
  );
  console.log(
    "[staging-flag-profile] 提示：profilePixelAvatarEnabled / equipmentRewardsEnabled / personalStoryEnabled 依赖对应迁移已应用到目标库。",
  );
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("[staging-flag-profile] 失败:", error);
    process.exit(1);
  });
